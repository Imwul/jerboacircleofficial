import type { Curiosity } from '../types';
import { getArchiveMediaAsset } from './mediaAssets';

function asset(id: string) {
  const found = getArchiveMediaAsset(id);
  if (!found) throw new Error(`Missing Cabinet source image: ${id}`);
  return found;
}

function sourcedCuriosity(
  assetId: string,
  record: Omit<Curiosity, 'image' | 'imageAlt' | 'source'> & {
    source?: Partial<Curiosity['source']>;
  },
): Curiosity {
  const media = asset(assetId);
  return {
    ...record,
    image: media.src,
    imageAlt: media.altText,
    source: {
      institution: record.source?.institution || media.repository,
      reference: record.source?.reference || media.repositoryObjectId,
      url: record.source?.url || media.sourceUrl,
    },
  };
}

